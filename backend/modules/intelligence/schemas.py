"""
modules/intelligence/schemas.py

Pydantic schemas for the AI-Powered Enterprise Intelligence module.
Defines foundational models for:
  - Executive intelligence recommendations
  - Project risk explanations (grounded in deterministic risk scores)
  - Sprint delay risk warnings
  - Workload bottleneck insights
  - Cross-module operational intelligence
  - AI generation metadata & disclaimers
"""

from datetime import datetime, timezone
from enum import Enum
from typing import List, Optional
from pydantic import BaseModel, Field


# --------------------------------------------------------------------------- #
# 1. Enums
# --------------------------------------------------------------------------- #

class RecommendationCategory(str, Enum):
    PROJECT = "project"
    WORKLOAD = "workload"
    INCIDENT = "incident"
    SUPPORT = "support"
    OPERATIONS = "operations"


class RiskLevel(str, Enum):
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"


class UrgencyLevel(str, Enum):
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"


class DelayStatus(str, Enum):
    ON_TRACK = "on_track"
    AT_RISK = "at_risk"
    DELAYED = "delayed"
    INSUFFICIENT_DATA = "insufficient_data"


class BottleneckSeverity(str, Enum):
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"


# --------------------------------------------------------------------------- #
# 2. Metadata & Advisory Wrapper
# --------------------------------------------------------------------------- #

class AIMetadata(BaseModel):
    """Metadata tracking AI model provenance, caching, and advisory status."""
    model_config = {"protected_namespaces": ()}

    model_provider: str = Field(default="gemini", max_length=50)
    model_name: str = Field(default="gemini-flash-lite-latest", max_length=100)
    generated_at: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="ISO 8601 UTC timestamp of generation",
    )
    is_cached: bool = Field(default=False)
    is_fallback: bool = Field(default=False, description="True if generated by deterministic heuristics")
    disclaimer: str = Field(
        default="AI recommendations are advisory only and require human review and approval. No automated business actions are executed.",
        max_length=255,
    )


# --------------------------------------------------------------------------- #
# 3. Executive Recommendations
# --------------------------------------------------------------------------- #

class ExecutiveRecommendationItem(BaseModel):
    """Structured 4-part executive insight synthesized from enterprise data."""
    id: str = Field(..., max_length=64, description="Unique identifier for the recommendation card")
    category: RecommendationCategory
    title: str = Field(..., min_length=3, max_length=150)
    observation: str = Field(..., min_length=5, max_length=500, description="What is currently happening in the business?")
    why_it_matters: str = Field(..., min_length=5, max_length=500, description="Why management should care about this trend")
    potential_consequence: str = Field(..., min_length=5, max_length=500, description="What could occur if left unaddressed?")
    recommended_preventive_action: str = Field(..., min_length=5, max_length=500, description="Concrete preventive action for leaders")
    urgency: UrgencyLevel = Field(default=UrgencyLevel.MEDIUM)
    requires_human_approval: bool = Field(default=True, description="Strictly True: all consequential actions require approval")


class ExecutiveSummaryResponse(BaseModel):
    """Organization-wide executive brief and actionable recommendations."""
    overall_status: str = Field(..., max_length=60, description="'healthy', 'attention_required', 'critical_attention'")
    executive_brief: str = Field(..., min_length=10, max_length=1500)
    recommendations: List[ExecutiveRecommendationItem] = Field(default_factory=list, max_length=10)
    metadata: AIMetadata = Field(default_factory=AIMetadata)


# --------------------------------------------------------------------------- #
# 4. Project Risk Explanations
# --------------------------------------------------------------------------- #

class ProjectRiskExplanationItem(BaseModel):
    """Project risk evaluation where numerical scores are deterministic,
    and Gemini explains root causes and recommendations."""
    project_id: int
    project_name: str = Field(..., max_length=150)
    deterministic_risk_level: RiskLevel = Field(description="Calculated by backend deterministic logic")
    deterministic_risk_score: float = Field(..., ge=0.0, le=100.0, description="Backend calculated metric 0-100")
    primary_risk_factors: List[str] = Field(default_factory=list, max_length=10)
    risk_explanation: str = Field(..., min_length=10, max_length=1000)
    potential_consequences: str = Field(..., min_length=5, max_length=500)
    recommended_actions: List[str] = Field(default_factory=list, max_length=6)


class ProjectRiskIntelligenceResponse(BaseModel):
    projects: List[ProjectRiskExplanationItem]
    metadata: AIMetadata = Field(default_factory=AIMetadata)


# --------------------------------------------------------------------------- #
# 5. Sprint Delay Intelligence
# --------------------------------------------------------------------------- #

class SprintDelayExplanationItem(BaseModel):
    """Sprint delay assessment grounded in duration, completion ratios, and overdue tasks."""
    sprint_id: int
    sprint_name: str = Field(..., max_length=150)
    project_name: str = Field(..., max_length=150)
    delay_status: DelayStatus
    delay_explanation: str = Field(..., min_length=10, max_length=1000)
    contributing_factors: List[str] = Field(default_factory=list, max_length=10)
    recommended_mitigations: List[str] = Field(default_factory=list, max_length=6)


class SprintDelayIntelligenceResponse(BaseModel):
    sprints: List[SprintDelayExplanationItem]
    metadata: AIMetadata = Field(default_factory=AIMetadata)


# --------------------------------------------------------------------------- #
# 6. Workload Bottleneck Intelligence
# --------------------------------------------------------------------------- #

class WorkloadBottleneckItem(BaseModel):
    """Workload imbalance detection across projects and teams without individual surveillance."""
    team_or_project: str = Field(..., max_length=150)
    bottleneck_severity: BottleneckSeverity
    observation: str = Field(..., min_length=5, max_length=500)
    affected_roles: List[str] = Field(default_factory=list, max_length=10, description="Role titles, never personal PII")
    suggested_balancing_action: str = Field(..., min_length=5, max_length=500)


class WorkloadIntelligenceResponse(BaseModel):
    bottlenecks: List[WorkloadBottleneckItem]
    metadata: AIMetadata = Field(default_factory=AIMetadata)


# --------------------------------------------------------------------------- #
# 7. Cross-Module Operations Intelligence
# --------------------------------------------------------------------------- #

class OperationsInsightsResponse(BaseModel):
    """Synthesis of Customer Support recurring friction and Incident vulnerability patterns."""
    support_insights: List[str] = Field(default_factory=list, max_length=10)
    incident_insights: List[str] = Field(default_factory=list, max_length=10)
    operational_summary: str = Field(..., min_length=10, max_length=1000)
    metadata: AIMetadata = Field(default_factory=AIMetadata)


# --------------------------------------------------------------------------- #
# 8. Cache Refresh Schemas
# --------------------------------------------------------------------------- #

class RefreshRequest(BaseModel):
    scope: str = Field(default="org", description="'org' or 'project'")
    project_id: Optional[int] = Field(default=None, description="Required if scope is 'project'")


class RefreshResponse(BaseModel):
    status: str = Field(..., description="'refreshed' or 'throttled'")
    message: str
    scope: str
    project_id: Optional[int] = None
    retry_after_seconds: Optional[float] = None

