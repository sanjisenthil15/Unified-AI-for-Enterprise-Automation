CREATE TYPE support_ticket_priority AS ENUM ('low', 'medium', 'high', 'critical');
CREATE TYPE support_ticket_status   AS ENUM ('open', 'in_progress', 'resolved', 'closed', 'escalated');
CREATE TYPE support_ticket_channel  AS ENUM ('web', 'email', 'chat', 'api');

CREATE TABLE support_tickets (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submitted_by BIGINT       NOT NULL
                     REFERENCES users (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    assigned_to  BIGINT       NULL
                     REFERENCES users (id) ON UPDATE CASCADE ON DELETE SET NULL,
    subject      VARCHAR(255) NOT NULL,
    description  TEXT         NOT NULL,
    priority     support_ticket_priority NOT NULL DEFAULT 'medium',
    status       support_ticket_status   NOT NULL DEFAULT 'open',
    channel      support_ticket_channel  NOT NULL DEFAULT 'web',
    resolved_at  TIMESTAMPTZ  NULL,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_support_tickets_submitted_by ON support_tickets (submitted_by);
CREATE INDEX ix_support_tickets_assigned_to  ON support_tickets (assigned_to);
CREATE INDEX ix_support_tickets_priority     ON support_tickets (priority);
CREATE INDEX ix_support_tickets_status       ON support_tickets (status);
CREATE TRIGGER trg_support_tickets_updated_at BEFORE UPDATE ON support_tickets
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

