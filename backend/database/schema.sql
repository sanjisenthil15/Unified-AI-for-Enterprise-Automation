-- 5. INCIDENT MANAGEMENT
-- =============================================================================

CREATE TYPE incident_severity AS ENUM ('low', 'medium', 'high', 'critical');
CREATE TYPE incident_status   AS ENUM ('open', 'investigating', 'resolved', 'closed');

CREATE TABLE incidents (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reported_by     BIGINT       NOT NULL
                        REFERENCES users (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    assigned_to     BIGINT       NULL
                        REFERENCES users (id) ON UPDATE CASCADE ON DELETE SET NULL,
    title           VARCHAR(255) NOT NULL,
    description     TEXT         NOT NULL,
    affected_system VARCHAR(120) NULL,
    root_cause      TEXT         NULL,
    severity        incident_severity NOT NULL DEFAULT 'medium',
    status          incident_status   NOT NULL DEFAULT 'open',
    resolved_at     TIMESTAMPTZ  NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_incidents_reported_by ON incidents (reported_by);
CREATE INDEX ix_incidents_assigned_to ON incidents (assigned_to);
CREATE INDEX ix_incidents_severity    ON incidents (severity);
CREATE INDEX ix_incidents_status      ON incidents (status);
CREATE TRIGGER trg_incidents_updated_at BEFORE UPDATE ON incidents
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

